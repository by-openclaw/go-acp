package mib

// Who a device was made by, whatever else is known about it: the IANA
// registry of private enterprise numbers, as tools/genpen compiled it. A
// sysObjectID sits under 1.3.6.1.4.1.<number>, so the number names the
// constructor with no MIB for the device at all, which is how an operator
// learns whose MIB to go and find. Names only: the registry's contacts and
// their addresses are not copied.

import (
	"bufio"
	"bytes"
	"compress/gzip"
	_ "embed"
	"fmt"
	"io"
	"strconv"
	"strings"
	"sync"

	"dhs/internal/snmp/codec"
)

// EnterpriseHeader starts the first line of the compiled registry; what
// follows it is the registry's own date. tools/genpen writes this constant
// and the reader refuses anything else.
const EnterpriseHeader = "# dhs-snmp-enterprises v1 — GENERATED by tools/genpen, do not edit — IANA "

//go:embed enterprises.tsv.gz
var enterpriseFile []byte

// enterprises opens the registry on first use: it is the largest thing in
// this package, and only `info` and a model walk ask it anything.
var enterprises = sync.OnceValue(func() map[uint32]string { return mustEnterprises(enterpriseFile) })

// mustEnterprises parses the registry this binary shipped with: see mustLoad.
func mustEnterprises(b []byte) map[uint32]string {
	m, err := parseEnterprises(bytes.NewReader(b))
	if err != nil {
		panic(err)
	}
	return m
}

// parseEnterprises reads the layout tools/genpen writes: gzip, the header
// line, then number TAB name.
func parseEnterprises(r io.Reader) (map[uint32]string, error) {
	zr, err := gzip.NewReader(r)
	if err != nil {
		return nil, fmt.Errorf("mib: enterprises: %w", err)
	}
	sc := bufio.NewScanner(zr)
	if !sc.Scan() || !strings.HasPrefix(sc.Text(), EnterpriseHeader) {
		return nil, fmt.Errorf("mib: enterprises: the first line does not start %q", EnterpriseHeader)
	}
	out := map[uint32]string{}
	for line := 2; sc.Scan(); line++ {
		number, name, _ := strings.Cut(sc.Text(), "\t")
		n, err := strconv.ParseUint(number, 10, 32)
		if err != nil {
			return nil, fmt.Errorf("mib: enterprises line %d: %w", line, err)
		}
		out[uint32(n)] = name
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("mib: enterprises: %w", err)
	}
	return out, nil
}

// Enterprise is the organisation IANA registered a number to.
func Enterprise(number uint32) (string, bool) {
	name, ok := enterprises()[number]
	return name, ok
}

// EnterpriseOf is the private enterprise number an OID sits under.
func EnterpriseOf(o codec.OID) (uint32, bool) {
	if len(o) <= len(Enterprises) || !o.HasPrefix(Enterprises) {
		return 0, false
	}
	return o[len(Enterprises)], true
}
