package codec

import "strings"

// Bitmap is one 64×32 button display (§1.2.6), pixel (x, y) with (0, 0)
// at the top-left as the operator sees it.
type Bitmap [32][64]bool

// Bitmap geometry.
const (
	BitmapW     = 64
	BitmapH     = 32
	BitmapBytes = 256
)

// Set turns one pixel on; out-of-range pixels are ignored.
func (b *Bitmap) Set(x, y int) {
	if x >= 0 && x < BitmapW && y >= 0 && y < BitmapH {
		b[y][x] = true
	}
}

// Encode returns the 256 bytes of a write-bitmap command (§1.2.6).
//
// §1.2.6 leaves the format to the button ("as defined for the button").
// Measured on the lab CCP-1601 (firmware DEL869-12) on 2026-10-25 by
// sending a known pattern and reading the display back by eye, then
// confirmed with the inverse: the button is driven column by column from
// the right edge (x = 63 first), 4 bytes per column; the 4 bytes are
// 8-row bands counted from the bottom with neighbouring bands swapped
// (byte 0 → rows 16-23, byte 1 → rows 24-31, byte 2 → rows 0-7,
// byte 3 → rows 8-15), and inside a band the MSB is the lowest row.
func (b *Bitmap) Encode() []byte {
	out := make([]byte, BitmapBytes)
	for y := 0; y < BitmapH; y++ {
		for x := 0; x < BitmapW; x++ {
			if !b[y][x] {
				continue
			}
			t := BitmapH - 1 - y
			byteInCol := (t / 8) ^ 1
			bit := 7 - t%8
			out[(BitmapW-1-x)*4+byteInCol] |= 1 << bit
		}
	}
	return out
}

// Decode is the inverse of Encode (used by tests and by a capture viewer).
func Decode(data []byte) Bitmap {
	var b Bitmap
	for k := 0; k < len(data) && k < BitmapBytes; k++ {
		for bit := 0; bit < 8; bit++ {
			if data[k]>>bit&1 == 0 {
				continue
			}
			x := BitmapW - 1 - k/4
			t := (k%4^1)*8 + (7 - bit)
			b[BitmapH-1-t][x] = true
		}
	}
	return b
}

// WriteBitmap builds command 0x06 for one button (§1.2.6).
func WriteBitmap(id byte, b *Bitmap) []byte {
	return append([]byte{CmdWriteBitmap, id}, b.Encode()...)
}

// String renders the bitmap as text, '#' on, '.' off (logs and tests).
func (b *Bitmap) String() string {
	var sb strings.Builder
	for y := 0; y < BitmapH; y++ {
		for x := 0; x < BitmapW; x++ {
			if b[y][x] {
				sb.WriteByte('#')
			} else {
				sb.WriteByte('.')
			}
		}
		sb.WriteByte('\n')
	}
	return sb.String()
}

// Text renders s on the button without a frame (see TextOpts).
func Text(s string) Bitmap { return TextOpts(s, false) }

// TextOpts renders one or more lines (split on '|' or '\n') centred on the
// button with the built-in 5×7 font. The largest scale at which every line
// fits whole is used — double size for up to 5 characters on 1-2 lines,
// normal size for up to 10 characters on up to 4 lines — so nothing is
// cropped. With frame set, a 1-pixel border is drawn and the text keeps a
// 1-pixel gap inside it (double size then holds 1 line of 4 characters or
// is dropped to normal size). Lines too long for normal size are cut.
func TextOpts(s string, frame bool) Bitmap { return TextScaled(s, frame, 0) }

// wrap splits a line longer than max at spaces (greedy), and a word longer
// than max at max.
func wrap(line string, max int) []string {
	if len(line) <= max {
		return []string{line}
	}
	var out []string
	cur := ""
	for _, w := range strings.Fields(line) {
		for len(w) > max {
			if cur != "" {
				out, cur = append(out, cur), ""
			}
			out, w = append(out, w[:max]), w[max:]
		}
		switch {
		case cur == "":
			cur = w
		case len(cur)+1+len(w) <= max:
			cur += " " + w
		default:
			out, cur = append(out, cur), w
		}
	}
	if cur != "" {
		out = append(out, cur)
	}
	return out
}

// TextScaled is TextOpts at a fixed scale (1 or 2); 0 picks the largest
// that fits. A fixed scale keeps a value's size steady while it changes
// (knobs); text that does not fit at a fixed scale 2 falls back to 1.
// Lines longer than the button holds are wrapped at spaces, not cut.
func TextScaled(s string, frame bool, fixed int) Bitmap {
	var b Bitmap
	if frame {
		for x := 0; x < BitmapW; x++ {
			b.Set(x, 0)
			b.Set(x, BitmapH-1)
		}
		for y := 0; y < BitmapH; y++ {
			b.Set(0, y)
			b.Set(BitmapW-1, y)
		}
	}
	lines := strings.FieldsFunc(s, func(r rune) bool { return r == '|' || r == '\n' })
	if len(lines) == 0 {
		return b
	}
	areaW, areaH := BitmapW, BitmapH
	if frame {
		areaW, areaH = BitmapW-4, BitmapH-4
	}
	// Wrap at the normal-size width first, so nothing is cut.
	var wrapped []string
	for _, l := range lines {
		wrapped = append(wrapped, wrap(l, (areaW+1)/6)...)
	}
	lines = wrapped
	longest := 0
	for _, l := range lines {
		if len(l) > longest {
			longest = len(l)
		}
	}
	fits := func(scale int) bool {
		return longest*6*scale-scale <= areaW && len(lines)*8*scale-scale <= areaH
	}
	scale := 1
	if (fixed == 0 || fixed == 2) && fits(2) {
		scale = 2
	}
	maxChars := (areaW + scale) / (6 * scale)
	maxLines := (areaH + scale) / (8 * scale)
	if len(lines) > maxLines {
		lines = lines[:maxLines]
	}
	lineH := 8 * scale
	blockH := len(lines)*lineH - scale
	top := (BitmapH - blockH) / 2
	for i, l := range lines {
		if len(l) > maxChars {
			l = l[:maxChars]
		}
		w := len(l)*6*scale - scale
		left := (BitmapW - w) / 2
		for j := 0; j < len(l); j++ {
			drawGlyph(&b, l[j], left+j*6*scale, top+i*lineH, scale)
		}
	}
	return b
}

func drawGlyph(b *Bitmap, c byte, x0, y0, scale int) {
	if c < 0x20 || c > 0x7E {
		c = '?'
	}
	g := font5x7[c-0x20]
	for col := 0; col < 5; col++ {
		for row := 0; row < 7; row++ {
			if g[col]>>row&1 == 0 {
				continue
			}
			for dx := 0; dx < scale; dx++ {
				for dy := 0; dy < scale; dy++ {
					b.Set(x0+col*scale+dx, y0+row*scale+dy)
				}
			}
		}
	}
}

