// LCDColour returns the SA6432 colour index for RGB levels 0..3 each
// (§1.2.5 footnote 1: 0b00 R1R0 G1G0 B1B0).
func LCDColour(r, g, b byte) byte { return (r&3)<<4 | (g&3)<<2 | b&3 }

// NamedColours are LCD button colours chosen BY EYE on the lab CCP-1601
