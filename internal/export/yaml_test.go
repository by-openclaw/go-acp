// TestWriteYAML_ACP1 — the exact document an ACP1 snapshot produces:
// device header, optional generator/protocol_version, then group →
// label → properties. Groups come from Group, then Path[0], then
// "other"; unlabeled objects are keyed obj_<id>; a duplicate label in
// one group keeps the last object; scalars needing quotes get them.
func TestWriteYAML_ACP1(t *testing.T) {
	snap := &Snapshot{
		Device:    DeviceInfo{IP: "10.6.239.113", Port: 2071, Protocol: "acp1", ProtocolVersion: 2, NumSlots: 1},
		Generator: "acp 1.0",
		CreatedAt: time.Date(2026, 4, 16, 12, 0, 0, 0, time.UTC),
		Slots: []SlotDump{{Slot: 1, Status: "present", WalkedAt: time.Date(2026, 4, 16, 12, 0, 0, 0, time.UTC),
			Objects: []consumer.Object{
				{Group: "control", Path: []string{"control"}, ID: 7, Label: "GainA", Kind: consumer.KindFloat, Access: 3, Unit: "%",
					Min: float64(0), Max: float64(150), Step: float64(1), Def: float64(100),
					Value: consumer.Value{Kind: consumer.KindFloat, Float: 50.8}},
				{Path: []string{"sensors"}, ID: 1, Label: "Temp", Kind: consumer.KindInt, Access: 1, Min: int64(-10), Max: int64(90),
					Value: consumer.Value{Kind: consumer.KindInt, Int: 42}},
				{Label: "Uptime", ID: 2, Kind: consumer.KindUint, Access: 1, Value: consumer.Value{Kind: consumer.KindUint, Uint: 99}},
				{Group: "identity", ID: 5, Kind: consumer.KindString, Access: 1, MaxLen: 8, Value: consumer.Value{Kind: consumer.KindString, Str: "RRS18"}},
				{Group: "control", Label: "Mode", ID: 8, Kind: consumer.KindEnum, Access: 3, EnumItems: []string{"Off", "On"}, Def: uint64(1),
					Value: consumer.Value{Kind: consumer.KindEnum, Enum: 1, Str: "On"}},
				{Group: "control", Label: "Mode", ID: 9, Kind: consumer.KindEnum, Access: 3, EnumItems: []string{"Off", "On"}, Def: uint64(1),
					Value: consumer.Value{Kind: consumer.KindEnum, Enum: 0}},
				{Group: "network", Label: "IP", ID: 3, Kind: consumer.KindIPAddr, Access: 1,
					Value: consumer.Value{Kind: consumer.KindIPAddr, IPAddr: [4]byte{10, 6, 250, 101}}},
				{Group: "frame", Label: "Slots", ID: 4, Kind: consumer.KindFrame, Access: 1,
					Value: consumer.Value{Kind: consumer.KindFrame, SlotStatus: []consumer.SlotStatus{consumer.SlotPresent, consumer.SlotNoCard}}},
				{Group: "frame", Label: "Empty frame", ID: 6, Kind: consumer.KindFrame, Access: 1, Value: consumer.Value{Kind: consumer.KindFrame}},
				{Group: "alarm", Label: "true", ID: 11, Kind: consumer.KindBool, Value: consumer.Value{Kind: consumer.KindBool, Bool: true}},
			}}},
	}
	want := `# acp snapshot — generated by cmd/acp
device:
  ip: 10.6.239.113
  port: 2071
  protocol: acp1
  protocol_version: 2
  num_slots: 1
generator: acp 1.0
created_at: "2026-04-16T12:00:00Z"
slots:
  - slot: 1
    status: present
    walked_at: "2026-04-16T12:00:00Z"
    control:
      GainA:
        id: 7
        kind: float
        access: RW-
        unit: "%"
        min: 0
        max: 150
        step: 1
        default: 100
        value: 50.8
      Mode:
        id: 9
        kind: enum
        access: RW-
        enum_items: ["Off", "On"]
        default: 1
        value: 0
    sensors:
      Temp:
        id: 1
        kind: int
        access: R--
        min: -10
        max: 90
        step: null
        default: null
        value: 42
    other:
      Uptime:
        id: 2
        kind: uint
        access: R--
        min: null
        max: null
        step: null
        default: null
        value: 99
    identity:
      obj_5:
        id: 5
        kind: string
        access: R--
        max_len: 8
        value: RRS18
    network:
      IP:
        id: 3
        kind: ipaddr
        access: R--
        value: 10.6.250.101
    frame:
      Slots:
        id: 4
        kind: frame
        access: R--
        slot_status:
          - {slot: 0, status: present}
          - {slot: 1, status: no_card}
      Empty frame:
        id: 6
        kind: frame
        access: R--
    alarm:
      "true":
        id: 11
        kind: bool
        access: ---
`
	var buf bytes.Buffer
	if err := WriteYAML(&buf, snap); err != nil {
		t.Fatalf("WriteYAML: %v", err)
	}
	if buf.String() != want {
		t.Errorf("YAML mismatch\n--- got ---\n%s\n--- want ---\n%s", buf.String(), want)
	}
}

// TestWriteYAML_ACP2 — an ACP2 snapshot drops the ROOT_NODE_V2 root
// object, nests every path segment, and renders containers (kind=raw)
// as bare maps around their leaves.
func TestWriteYAML_ACP2(t *testing.T) {
	snap := &Snapshot{
		Device:    DeviceInfo{IP: "10.41.40.195", Port: 2072, Protocol: "acp2", NumSlots: 1},
		CreatedAt: time.Date(2026, 4, 19, 12, 0, 0, 0, time.UTC),
		Slots: []SlotDump{{Slot: 0, WalkedAt: time.Date(2026, 4, 19, 12, 0, 0, 0, time.UTC),
			Objects: []consumer.Object{
				{Path: []string{"ROOT_NODE_V2"}, ID: 1, Label: "ROOT_NODE_V2", Kind: consumer.KindRaw},
				{Path: []string{"ROOT_NODE_V2", "BOARD"}, ID: 2, Label: "BOARD", Kind: consumer.KindRaw},
				{Path: []string{"ROOT_NODE_V2", "BOARD", "ACP Trace"}, ID: 47431, Label: "ACP Trace", Kind: consumer.KindEnum, Access: 3,
					EnumItems: []string{"Off", "On"}, Value: consumer.Value{Kind: consumer.KindEnum, Enum: 0, Str: "Off"}},
				{Path: []string{"ROOT_NODE_V2", "STATUS", "PSU", "1", "Present"}, ID: 60001, Label: "Present", Kind: consumer.KindString, Access: 1,
					Value: consumer.Value{Kind: consumer.KindString, Str: "yes: maybe"}},
			}}},
	}
	want := `# acp snapshot — generated by cmd/acp
device:
  ip: 10.41.40.195
  port: 2072
  protocol: acp2
  num_slots: 1
created_at: "2026-04-19T12:00:00Z"
slots:
  - slot: 0
    walked_at: "2026-04-19T12:00:00Z"
    BOARD:
      ACP Trace:
        id: 47431
        kind: enum
        access: RW-
        enum_items: ["Off", "On"]
        default: null
        value: 0
        value_name: "Off"
    STATUS:
      PSU:
        1:
          Present:
            id: 60001
            kind: string
            access: R--
            value: "yes: maybe"
`
	var buf bytes.Buffer
	if err := WriteYAML(&buf, snap); err != nil {
		t.Fatalf("WriteYAML: %v", err)
	}
	if buf.String() != want {
		t.Errorf("YAML mismatch\n--- got ---\n%s\n--- want ---\n%s", buf.String(), want)
	}
	// And the reader takes it back: the tree is the contract both ways.
	back, err := ReadYAML(strings.NewReader(buf.String()))
	if err != nil {
		t.Fatalf("ReadYAML: %v", err)
	}
	var leaves []string
	for _, o := range back.Slots[0].Objects {
		if o.ID != 0 {
			leaves = append(leaves, strings.Join(o.Path, "."))
		}
	}
	if got := strings.Join(leaves, ","); got != "BOARD.ACP Trace,STATUS.PSU.1.Present" {
		t.Errorf("read-back leaf paths: %s", got)
	}
}

